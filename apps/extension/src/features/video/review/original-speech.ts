import { isRecord } from '@sniptale/runtime-contracts/validation/primitives';
import type { QuickEditAudioClip } from './advanced/types';
import type { ReviewTimeSegment } from './time-segment';
import type {
  ReviewOriginalSpeechReplacement,
  ReviewOriginalSpeechTranscript,
  ReviewOriginalSpeech,
} from './speech-transcript';
import { parseReviewSpeechReplacement, parseReviewSpeechTranscript } from './speech-validation';

export type {
  ReviewOriginalSpeechReplacement,
  ReviewOriginalSpeechTranscript,
  ReviewOriginalSpeech,
} from './speech-transcript';

function parseOriginalReplacement(value: unknown): ReviewOriginalSpeechReplacement | null {
  const replacement = parseReviewSpeechReplacement(value);
  if (
    !replacement ||
    !isRecord(value) ||
    (value['enabled'] !== undefined && typeof value['enabled'] !== 'boolean') ||
    typeof value['originalVolume'] !== 'number' ||
    !Number.isFinite(value['originalVolume']) ||
    value['originalVolume'] < 0 ||
    value['originalVolume'] > 1
  )
    return null;
  return {
    ...replacement,
    enabled: value['enabled'] ?? true,
    originalVolume: value['originalVolume'],
  };
}

/** Reuses the strict transcript envelope while retaining original-only replacement semantics. */
export function parseReviewOriginalSpeechTranscript(
  value: unknown
): ReviewOriginalSpeechTranscript | null {
  return parseReviewSpeechTranscript(value, parseOriginalReplacement);
}

/** Older omission is handled by the containing audio codec; explicit malformed state is rejected. */
export function parseReviewOriginalSpeech(value: unknown): ReviewOriginalSpeech | null {
  if (!isRecord(value) || typeof value['enabled'] !== 'boolean') return null;
  const transcript = parseReviewOriginalSpeechTranscript(value['transcript']);
  return transcript ? { enabled: value['enabled'], transcript } : null;
}

/** Projects generated bytes once through Cut/Speed while attenuation retains whole native slots. */
export function projectOriginalSpeech(args: {
  speech: ReviewOriginalSpeech | undefined;
  timeMap: readonly ReviewTimeSegment[];
}): {
  clips: QuickEditAudioClip[];
  originalRanges: readonly { start: number; end: number; volume: number }[];
} {
  const clips: QuickEditAudioClip[] = [];
  const originalRanges: { start: number; end: number; volume: number }[] = [];
  if (!args.speech?.enabled) return { clips, originalRanges };
  for (const replacement of args.speech.transcript.replacements) {
    if (!replacement.enabled) continue;
    originalRanges.push({
      start: replacement.start,
      end: replacement.end,
      volume: replacement.originalVolume,
    });
    for (const segment of args.timeMap) {
      if (segment.kind === 'cut') continue;
      const start = Math.max(replacement.start, segment.sourceStart);
      const end = Math.min(replacement.start + replacement.duration, segment.sourceEnd);
      if (end <= start) continue;
      clips.push({
        id: `revoice:${replacement.id}:${start}`,
        assetId: replacement.assetId,
        sourceOffset: start - replacement.start,
        timelineStart: segment.resultStart + (start - segment.sourceStart) / segment.rate,
        duration: (end - start) / segment.rate,
        playbackRate: segment.rate,
        volume: 1,
        muted: false,
        fadeIn: 0,
        fadeOut: 0,
      });
    }
  }
  return { clips, originalRanges };
}
