import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import Ajv2020 from 'ajv/dist/2020.js';
import standaloneCode from 'ajv/dist/standalone/index.js';
import { build } from 'esbuild';
import type { Plugin } from 'vite';

const DIRECTORY = fileURLToPath(
  new URL('../../../packages/runtime-contracts/src/animation-template/', import.meta.url)
);

/** Compile the pinned upstream schema on the build host; the browser receives executable validation only. */
export async function generateLottieSchema(): Promise<void> {
  const source = await readFile(resolve(DIRECTORY, 'lottie-schema.source.json'));
  const identity: unknown = JSON.parse(
    await readFile(resolve(DIRECTORY, 'lottie-schema.identity.json'), 'utf8')
  );
  if (
    identity === null ||
    typeof identity !== 'object' ||
    !('sha256' in identity) ||
    identity.sha256 !== createHash('sha256').update(source).digest('hex')
  )
    throw new Error('Lottie schema identity does not match its pinned source.');
  // Upstream uses documentary extension keywords. All validation keywords remain enabled.
  const ajv = new Ajv2020({ strict: false, allErrors: false, code: { source: true, esm: true } });
  const schema: unknown = JSON.parse(source.toString('utf8'));
  // The upstream sound branch also matches ordinary images. Its oneOf is ambiguous.
  // Sniptale admits only image/precomposition assets, so compile that strict supported subset.
  if (
    schema === null ||
    typeof schema !== 'object' ||
    !('$defs' in schema) ||
    schema.$defs === null ||
    typeof schema.$defs !== 'object' ||
    !('assets' in schema.$defs) ||
    schema.$defs.assets === null ||
    typeof schema.$defs.assets !== 'object' ||
    !('all-assets' in schema.$defs.assets)
  )
    throw new Error('Lottie asset schema shape differs.');
  const assets = schema.$defs.assets['all-assets'];
  if (
    assets === null ||
    typeof assets !== 'object' ||
    !('oneOf' in assets) ||
    !Array.isArray(assets.oneOf)
  )
    throw new Error('Lottie asset schema union differs.');
  const supported = assets.oneOf.filter(
    (entry: unknown) =>
      entry !== null &&
      typeof entry === 'object' &&
      '$ref' in entry &&
      (entry.$ref === '#/$defs/assets/precomposition' || entry.$ref === '#/$defs/assets/image')
  );
  if (supported.length !== 2 || assets.oneOf.length !== 4)
    throw new Error('Lottie supported asset schema differs.');
  assets.oneOf = supported;
  const validator = ajv.compile(schema);
  const result = await build({
    stdin: {
      contents: standaloneCode(ajv, validator),
      resolveDir: process.cwd(),
      sourcefile: 'lottie-schema.standalone.js',
    },
    bundle: true,
    write: false,
    platform: 'browser',
    format: 'esm',
    target: 'es2024',
    minify: false,
    legalComments: 'inline',
    banner: {
      js: [
        '/* Generated by apps/extension/build/lottie-schema.ts.',
        'LottieFiles/lottie-docs schema, Sniptale image/precomposition profile:',
        'CC-BY-4.0; Ajv: MIT. See lottie-schema.LICENSE.txt. */',
      ].join(' '),
    },
  });
  const generated = result.outputFiles?.[0]?.text;
  if (!generated) throw new Error('Lottie standalone generation produced no module.');
  const destination = resolve(DIRECTORY, 'lottie-schema.generated.js');
  const previous = await readFile(destination, 'utf8').catch(() => '');
  if (previous !== generated) await writeFile(destination, generated);
}

export function lottieSchema(): Plugin {
  return {
    name: 'sniptale:lottie-schema',
    async buildStart() {
      await generateLottieSchema();
    },
  };
}

if (process.argv[1] && pathToFileURL(resolve(process.argv[1])).href === import.meta.url)
  await generateLottieSchema();
